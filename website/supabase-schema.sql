-- =========================================================================
-- 1. DELETE EXISTING DUPLICATE DATA (Retains newest row per mobile/email)
-- =========================================================================

-- Deduplicate visitor_registrations
DELETE FROM public.visitor_registrations
WHERE id NOT IN (
    SELECT MAX(id)
    FROM public.visitor_registrations
    GROUP BY mobile
);

DELETE FROM public.visitor_registrations
WHERE email IS NOT NULL AND email <> '' AND id NOT IN (
    SELECT MAX(id)
    FROM public.visitor_registrations
    WHERE email IS NOT NULL AND email <> ''
    GROUP BY email
);

-- Deduplicate exhibitor_registrations
DELETE FROM public.exhibitor_registrations
WHERE id NOT IN (
    SELECT MAX(id)
    FROM public.exhibitor_registrations
    GROUP BY mobile
);

DELETE FROM public.exhibitor_registrations
WHERE email IS NOT NULL AND email <> '' AND id NOT IN (
    SELECT MAX(id)
    FROM public.exhibitor_registrations
    WHERE email IS NOT NULL AND email <> ''
    GROUP BY email
);

-- Deduplicate pre_registrations
DELETE FROM public.pre_registrations
WHERE id NOT IN (
    SELECT MAX(id)
    FROM public.pre_registrations
    GROUP BY mobile
);

DELETE FROM public.pre_registrations
WHERE email IS NOT NULL AND email <> '' AND id NOT IN (
    SELECT MAX(id)
    FROM public.pre_registrations
    WHERE email IS NOT NULL AND email <> ''
    GROUP BY email
);

-- Deduplicate sub_event_registrations
DELETE FROM public.sub_event_registrations
WHERE id NOT IN (
    SELECT MAX(id)
    FROM public.sub_event_registrations
    GROUP BY mobile, COALESCE(event_slug, '')
);

-- =========================================================================
-- 2. CREATE UNIQUE INDEXES FOR DUPLICATE PREVENTION (Mobile & Email)
-- =========================================================================

CREATE UNIQUE INDEX IF NOT EXISTS idx_visitor_mobile_unique ON public.visitor_registrations (mobile);
CREATE UNIQUE INDEX IF NOT EXISTS idx_visitor_email_unique ON public.visitor_registrations (email) WHERE email IS NOT NULL AND email <> '';

CREATE UNIQUE INDEX IF NOT EXISTS idx_exhibitor_mobile_unique ON public.exhibitor_registrations (mobile);
CREATE UNIQUE INDEX IF NOT EXISTS idx_exhibitor_email_unique ON public.exhibitor_registrations (email) WHERE email IS NOT NULL AND email <> '';

CREATE UNIQUE INDEX IF NOT EXISTS idx_pre_mobile_unique ON public.pre_registrations (mobile);
CREATE UNIQUE INDEX IF NOT EXISTS idx_pre_email_unique ON public.pre_registrations (email) WHERE email IS NOT NULL AND email <> '';

CREATE UNIQUE INDEX IF NOT EXISTS idx_sub_mobile_event_unique ON public.sub_event_registrations (mobile, COALESCE(event_slug, ''));



