-- 1. Pre-Registrations Table
CREATE TABLE IF NOT EXISTS public.pre_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    name TEXT NOT NULL,
    country_code TEXT,
    mobile TEXT NOT NULL,
    email TEXT,
    city TEXT,
    category TEXT,
    days TEXT
);

-- 2. Visitor Registrations Table
CREATE TABLE IF NOT EXISTS public.visitor_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    name TEXT NOT NULL,
    country_code TEXT,
    mobile TEXT NOT NULL,
    email TEXT,
    visit_profile TEXT,
    company_name TEXT,
    designation TEXT,
    address TEXT,
    city TEXT,
    district TEXT,
    state TEXT,
    pincode TEXT,
    landmark TEXT,
    days TEXT
);

-- 3. Exhibitor Registrations Table
CREATE TABLE IF NOT EXISTS public.exhibitor_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    name TEXT NOT NULL,
    designation TEXT,
    company_name TEXT,
    mobile TEXT NOT NULL,
    email TEXT,
    address TEXT,
    pincode TEXT,
    city TEXT,
    state TEXT,
    country TEXT,
    days TEXT
);

